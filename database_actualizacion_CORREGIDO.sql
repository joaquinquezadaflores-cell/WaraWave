-- Crea o enlaza automáticamente el perfil cuando alguien se registra
-- mediante Supabase Auth. Si el correo ya existía en la tabla antigua,
-- conserva su id y, por lo tanto, también su historial de reportes.
create or replace function public.sincronizar_usuario_auth()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    nombre_nuevo text;
begin
    nombre_nuevo := coalesce(
        nullif(new.raw_user_meta_data ->> 'nombre', ''),
        split_part(new.email, '@', 1)
    );

    update public.usuarios
       set auth_id = new.id,
           nombre = coalesce(nullif(nombre, ''), nombre_nuevo),
           correo = lower(new.email),
           password = null,
           activo = true
     where lower(correo) = lower(new.email)
       and (auth_id is null or auth_id = new.id);

    if not found then
        insert into public.usuarios (
            auth_id, nombre, correo, password, rol, activo
        ) values (
            new.id, nombre_nuevo, lower(new.email), null, 'ciudadano', true
        );
    end if;

    return new;
end;
$$;

drop trigger if exists al_crear_usuario_auth on auth.users;
create trigger al_crear_usuario_auth
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function public.sincronizar_usuario_auth();

-- Enlaza cuentas de Auth que ya existan antes de ejecutar este archivo.
update public.usuarios u
   set auth_id = a.id,
       password = null
  from auth.users a
 where lower(u.correo) = lower(a.email)
   and u.auth_id is null;

insert into public.usuarios (auth_id, nombre, correo, password, rol, activo)
select
    a.id,
    coalesce(nullif(a.raw_user_meta_data ->> 'nombre', ''), split_part(a.email, '@', 1)),
    lower(a.email),
    null,
    'ciudadano',
    true
from auth.users a
where not exists (
    select 1 from public.usuarios u where u.auth_id = a.id
);

