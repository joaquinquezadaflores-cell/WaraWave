-- USUARIOS
drop policy if exists usuarios_leer_perfil_o_admin on public.usuarios;
create policy usuarios_leer_perfil_o_admin
on public.usuarios for select
to authenticated
using (
    auth_id = auth.uid()
    or public.mi_rol() = 'administrador'
);

drop policy if exists usuarios_actualizar_admin on public.usuarios;
create policy usuarios_actualizar_admin
on public.usuarios for update
to authenticated
using (public.mi_rol() = 'administrador')
with check (rol in ('ciudadano', 'administrador', 'autoridad'));

-- REPORTES
drop policy if exists reportes_leer_permitidos on public.reportes;
create policy reportes_leer_permitidos
on public.reportes for select
to authenticated
using (
    activo = true
    or usuario_id = public.mi_usuario_id()
    or public.mi_rol() in ('administrador', 'autoridad')
);

drop policy if exists reportes_crear_propios on public.reportes;
create policy reportes_crear_propios
on public.reportes for insert
to authenticated
with check (
    usuario_id = public.mi_usuario_id()
    and activo = true
);

drop policy if exists reportes_moderar_admin on public.reportes;
create policy reportes_moderar_admin
on public.reportes for update
to authenticated
using (public.mi_rol() = 'administrador')
with check (public.mi_rol() = 'administrador');

drop policy if exists reportes_eliminar_admin on public.reportes;
create policy reportes_eliminar_admin
on public.reportes for delete
to authenticated
using (public.mi_rol() = 'administrador');

