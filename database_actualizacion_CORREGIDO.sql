-- Registra automáticamente cuándo se modera/restaura un reporte.
create or replace function public.registrar_fecha_moderacion()
returns trigger
language plpgsql
as $$
begin
    if old.activo is distinct from new.activo then
        new.fecha_moderacion := now();
    end if;
    return new;
end;
$$;

drop trigger if exists antes_de_moderar_reporte on public.reportes;
create trigger antes_de_moderar_reporte
before update of activo on public.reportes
for each row execute function public.registrar_fecha_moderacion();

-- 3) CONFIRMACIONES ÚNICAS (UN USUARIO, UNA CONFIRMACIÓN)
create table if not exists public.confirmaciones (
    id bigint generated by default as identity primary key,
    reporte_id bigint not null references public.reportes(id) on delete cascade,
    usuario_id bigint not null references public.usuarios(id) on delete cascade,
    fecha timestamptz not null default now(),
    constraint confirmacion_unica unique (reporte_id, usuario_id)
);

create or replace function public.validar_confirmacion()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if exists (
        select 1
          from public.reportes r
         where r.id = new.reporte_id
           and r.usuario_id = new.usuario_id
    ) then
        raise exception 'El autor no puede confirmar su propio reporte';
    end if;

    if not exists (
        select 1
          from public.reportes r
         where r.id = new.reporte_id
           and r.activo = true
    ) then
        raise exception 'Solo se pueden confirmar reportes visibles';
    end if;

    return new;
end;
$$;

drop trigger if exists antes_de_confirmar_reporte on public.confirmaciones;
create trigger antes_de_confirmar_reporte
before insert on public.confirmaciones
for each row execute function public.validar_confirmacion();

create or replace function public.actualizar_total_confirmaciones()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if tg_op = 'INSERT' then
        update public.reportes
           set me_sirve = coalesce(me_sirve, 0) + 1
         where id = new.reporte_id;
        return new;
    elsif tg_op = 'DELETE' then
        update public.reportes
           set me_sirve = greatest(coalesce(me_sirve, 0) - 1, 0)
         where id = old.reporte_id;
        return old;
    end if;
    return null;
end;
$$;

drop trigger if exists despues_de_confirmar_reporte on public.confirmaciones;
create trigger despues_de_confirmar_reporte
after insert or delete on public.confirmaciones
for each row execute function public.actualizar_total_confirmaciones();

-- 4) FUNCIONES AUXILIARES PARA POLÍTICAS RLS
create or replace function public.mi_usuario_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
    select id
      from public.usuarios
     where auth_id = auth.uid()
       and activo = true
     limit 1;
$$;

create or replace function public.mi_rol()
returns text
language sql
stable
security definer
set search_path = public
as $$
    select rol
      from public.usuarios
     where auth_id = auth.uid()
       and activo = true
     limit 1;
$$;

grant execute on function public.mi_usuario_id() to authenticated;
grant execute on function public.mi_rol() to authenticated;

-- 5) LIMPIEZA DE POLÍTICAS ANTIGUAS Y ROW LEVEL SECURITY
-- El proyecto anterior tenía políticas muy permisivas (USING/WITH CHECK true).
-- Las quitamos para que no anulen las políticas seguras definidas más abajo.
do $$
declare
    politica record;
begin
    for politica in
        select schemaname, tablename, policyname
          from pg_policies
         where schemaname = 'public'
           and tablename in ('usuarios', 'reportes', 'confirmaciones')
    loop
        execute format(
            'drop policy if exists %I on %I.%I',
            politica.policyname,
            politica.schemaname,
            politica.tablename
        );
    end loop;
end;
$$;

-- Quita únicamente las políticas antiguas asociadas al bucket de WaraWave.
do $$
declare
    politica record;
begin
    for politica in
        select policyname
          from pg_policies
         where schemaname = 'storage'
           and tablename = 'objects'
           and (
                policyname ilike '%reportes imagenes%'
                or coalesce(qual, '') ilike '%reportes-imagenes%'
                or coalesce(with_check, '') ilike '%reportes-imagenes%'
           )
    loop
        execute format(
            'drop policy if exists %I on storage.objects',
            politica.policyname
        );
    end loop;
end;
$$;

